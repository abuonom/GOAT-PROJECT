// GM di test aggiunge un rookie dal form della pagina roster e verifica che compaia nel roster.
import { chromium } from 'playwright'
const [base, email, password] = process.argv.slice(2)
const browser = await chromium.launch()
const page = await browser.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
await page.goto(base + '/login', { waitUntil: 'networkidle' })
await page.fill('input[type="email"]', email)
await page.fill('input[type="password"]', password)
await page.getByRole('button', { name: /accedi/i }).last().click()
await page.waitForURL(u => !u.toString().includes('/login'), { timeout: 30000 })
await page.goto(base + '/roster', { waitUntil: 'networkidle', timeout: 60000 })
await page.getByRole('button', { name: /Aggiungi rookie/ }).click()
await page.fill('input[placeholder="Nome"]', 'Christian Collins')
await page.fill('input[placeholder="Overall (40–99)"]', '74')
await page.fill('input[placeholder="Anno draft"]', '2027')
await page.getByRole('button', { name: 'SF' }).click()
await page.getByRole('button', { name: 'Aggiungi al roster' }).click()
await page.waitForTimeout(3000)
await page.waitForFunction(() => document.body.innerText.includes('Giocatori'), null, { timeout: 30000 })
await page.waitForTimeout(1500)
const rows = await page.evaluate(async () => (await (await fetch('/api/roster/full')).json()).memberships.map(m => m.player_slug))
const text = await page.textContent('body')
console.log(JSON.stringify({ rookieInRoster: rows.some(s => s.startsWith('rookie-2027-christian-collins')), rosterRows: rows.length, shownName: text.includes('Christian Collins'), errorBanner: text.includes('Error:'), pageErrors: errors }))
await browser.close()

// Dal roster, cerca un giocatore nella pagina e lo aggiunge con "+ Aggiungi". Verifica il conteggio.
import { chromium } from 'playwright'
const [base, email, password, query] = process.argv.slice(2)
const browser = await chromium.launch()
const page = await browser.newPage()
await page.goto(base + '/login', { waitUntil: 'networkidle' })
await page.fill('input[type="email"]', email)
await page.fill('input[type="password"]', password)
await page.getByRole('button', { name: /accedi/i }).last().click()
await page.waitForURL(u => !u.toString().includes('/login'), { timeout: 30000 })
await page.goto(base + '/roster', { waitUntil: 'networkidle', timeout: 60000 })
const count = () => page.evaluate(async () => (await (await fetch('/api/roster/full')).json()).memberships.length)
const before = await count()
await page.fill('input[placeholder="Cerca per nome…"]', query)
await page.waitForTimeout(500)
await page.getByRole('button', { name: '+ Aggiungi' }).first().click()
await page.waitForTimeout(2000)
const after = await count()
console.log(JSON.stringify({ before, after, addedInPage: after === before + 1 }))
await browser.close()

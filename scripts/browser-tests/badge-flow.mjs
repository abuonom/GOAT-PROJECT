// Flusso badge Bronzo→Argento con account di prova (0 GC): deve arrivare alla conferma e il server deve rifiutare per saldo.
import { chromium } from 'playwright'
const [base, email, password] = process.argv.slice(2)
const browser = await chromium.launch()
const page = await browser.newPage()
const api = []
page.on('response', r => { if (r.url().includes('/api/gm-roster') && r.request().method() === 'POST') api.push({ status: r.status() }) })
await page.goto(base + '/login', { waitUntil: 'networkidle' })
await page.fill('input[type="email"]', email)
await page.fill('input[type="password"]', password)
await page.getByRole('button', { name: /accedi/i }).last().click()
await page.waitForURL(u => !u.toString().includes('/login'), { timeout: 30000 })
await page.goto(base + '/gm-shop', { waitUntil: 'networkidle', timeout: 90000 })
await page.locator('button', { hasText: /Jok/ }).first().click()
await page.locator('button', { hasText: /^Badge$/ }).first().click()
await page.waitForTimeout(300)
await page.locator('button', { hasText: /Bronzo/ }).first().click()
await page.locator('input[placeholder="Es. Set and Fire"]').fill('Set and Fire')
await page.getByRole('button', { name: 'Continua' }).click()
const cartellino = await page.locator('body').textContent()
const confirm = page.getByRole('button', { name: 'Conferma upgrade' })
const confirmEnabled = await confirm.isEnabled()
console.log(JSON.stringify({ riepilogoHaCartellino: cartellino.includes('Set and Fire'), confirmEnabled, nota: 'saldo 0 GC: il pulsante va disabilitato' }, null, 2))
await browser.close()
